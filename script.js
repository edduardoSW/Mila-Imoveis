let activeCustomSelect = null;
let selectPopover = null;

function ensureSelectPopover(dialog = null) {
  if (!selectPopover) {
    selectPopover = document.createElement("div");
    selectPopover.className = "select-popover";
    selectPopover.id = "select-popover";
    selectPopover.setAttribute("role", "listbox");
    selectPopover.hidden = true;
  }
  const host = dialog || document.body;
  if (selectPopover.parentElement !== host) host.appendChild(selectPopover);
  return selectPopover;
}

function syncCustomSelect(select) {
  const button = select.closest(".custom-select-shell")?.querySelector(".custom-select-button");
  if (button) button.querySelector("span").textContent = select.selectedOptions[0]?.textContent || "Selecione";
}

function positionSelectPopover(button) {
  if (!selectPopover || selectPopover.hidden) return;
  const rect = button.getBoundingClientRect();
  const margin = 8;
  const below = window.innerHeight - rect.bottom - margin;
  const above = rect.top - margin;
  const openAbove = below < 180 && above > below;
  const available = Math.max(132, Math.min(320, openAbove ? above : below));
  const width = Math.min(Math.max(rect.width, 190), window.innerWidth - margin * 2);
  const left = Math.max(margin, Math.min(rect.left, window.innerWidth - width - margin));
  selectPopover.style.width = `${width}px`;
  selectPopover.style.maxHeight = `${available}px`;
  selectPopover.style.left = `${left}px`;
  selectPopover.style.top = openAbove ? `${Math.max(margin, rect.top - Math.min(selectPopover.scrollHeight, available) - 6)}px` : `${rect.bottom + 6}px`;
}

function closeCustomSelect({ returnFocus = false } = {}) {
  if (!activeCustomSelect || !selectPopover) return;
  const { button } = activeCustomSelect;
  button.setAttribute("aria-expanded", "false");
  selectPopover.hidden = true;
  selectPopover.innerHTML = "";
  activeCustomSelect = null;
  if (returnFocus) button.focus();
}

function chooseCustomOption(index) {
  if (!activeCustomSelect) return;
  const { select, button } = activeCustomSelect;
  const option = select.options[index];
  if (!option || option.disabled) return;
  select.selectedIndex = index;
  button.querySelector("span").textContent = option.textContent;
  select.dispatchEvent(new Event("change", { bubbles: true }));
  closeCustomSelect({ returnFocus: true });
}

function openCustomSelect(select, button, focusIndex = select.selectedIndex) {
  if (activeCustomSelect?.select === select) {
    closeCustomSelect({ returnFocus: true });
    return;
  }
  closeCustomSelect();
  const popover = ensureSelectPopover(select.closest("dialog[open]"));
  popover.innerHTML = [...select.options].map((option, index) => `<button class="select-option" type="button" role="option" data-option-index="${index}" aria-selected="${index === select.selectedIndex}" ${option.disabled ? "disabled" : ""}>${option.textContent}</button>`).join("");
  popover.hidden = false;
  button.setAttribute("aria-expanded", "true");
  activeCustomSelect = { select, button };
  positionSelectPopover(button);
  const options = [...popover.querySelectorAll(".select-option:not(:disabled)")];
  const target = popover.querySelector(`[data-option-index="${focusIndex}"]:not(:disabled)`) || options[0];
  target?.focus({ preventScroll: true });
  target?.scrollIntoView({ block: "nearest" });
}

function enhanceSelects(root = document) {
  root.querySelectorAll("select:not([data-enhanced])").forEach(select => {
    select.dataset.enhanced = "true";
    select.classList.add("native-select-hidden");
    const shell = document.createElement("div");
    shell.className = "custom-select-shell";
    select.before(shell);
    shell.appendChild(select);
    const button = document.createElement("button");
    button.className = "custom-select-button";
    button.type = "button";
    button.setAttribute("aria-haspopup", "listbox");
    button.setAttribute("aria-expanded", "false");
    button.setAttribute("aria-controls", "select-popover");
    button.innerHTML = `<span>${select.selectedOptions[0]?.textContent || "Selecione"}</span>`;
    shell.prepend(button);
    button.addEventListener("click", event => {
      event.stopPropagation();
      openCustomSelect(select, button);
    });
    button.addEventListener("keydown", event => {
      if (!["ArrowDown", "ArrowUp", "Home", "End", "Enter", " "].includes(event.key)) return;
      event.preventDefault();
      const last = select.options.length - 1;
      const index = event.key === "ArrowUp" ? Math.max(0, select.selectedIndex - 1) : event.key === "Home" ? 0 : event.key === "End" ? last : Math.min(last, Math.max(0, select.selectedIndex));
      openCustomSelect(select, button, index);
    });
    select.addEventListener("change", () => syncCustomSelect(select));
  });
}

function setupHeroVideo() {
  const video = document.querySelector(".hero-video");
  if (!video) return;
  const hero = video.closest(".hero");
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

  const showVideo = () => {
    if (!video.isConnected || video.readyState < HTMLMediaElement.HAVE_CURRENT_DATA || video.paused) return;
    hero.classList.add("is-video-ready");
  };

  const keepCover = () => {
    hero.classList.remove("is-video-ready");
    hero.classList.add("is-video-unavailable");
  };

  video.addEventListener("playing", showVideo);
  video.addEventListener("loadeddata", showVideo);
  video.addEventListener("error", keepCover, { once: true });

  if (reduceMotion) {
    video.pause();
    video.removeAttribute("autoplay");
  } else {
    video.play().then(showVideo).catch(keepCover);
  }
}

function setupShortcutReveal() {
  const items = document.querySelectorAll(".shortcut-item");
  if (!items.length) return;
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches || !("IntersectionObserver" in window)) {
    items.forEach(item => item.classList.add("is-visible"));
    return;
  }
  const observer = new IntersectionObserver(entries => {
    entries.forEach(entry => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("is-visible");
      observer.unobserve(entry.target);
    });
  }, { threshold: 0.2 });
  items.forEach(item => observer.observe(item));
}

