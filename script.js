function readFavorites() {
  try { return JSON.parse(localStorage.getItem("mila-favorites")) || []; }
  catch { return []; }
}

function saveFavorites() {
  localStorage.setItem("mila-favorites", JSON.stringify(favorites));
  updateFavoriteCount();
}

function updateFavoriteCount() {
  const count = document.querySelector(".favorite-count");
  count.textContent = favorites.length;
  count.setAttribute("aria-label", `${favorites.length} ${favorites.length === 1 ? "favorito" : "favoritos"}`);
}

function currency(value) {
  return new Intl.NumberFormat("pt-BR", { style: "currency", currency: "BRL", maximumFractionDigits: Number(value) % 1 ? 2 : 0 }).format(value);
}

function decimal(value) {
  return new Intl.NumberFormat("pt-BR", { maximumFractionDigits: 2 }).format(value);
}

function plural(value, singular, pluralForm) {
  return `${value} ${value === 1 ? singular : pluralForm}`;
}

function costs(property) {
  const parts = [];
  if (property.condo) parts.push(`Condomínio ${currency(property.condo)}`);
  if (property.iptu) parts.push(`IPTU ${currency(property.iptu)}${property.iptuPeriod === "YEARLY" ? "/ano" : property.iptuPeriod === "MONTHLY" ? "/mês" : ""}`);
  return parts.length ? parts.join(" · ") : "Despesas adicionais sob consulta";
}

function purposeLabel(property) {
  if (property.purpose === "alugar") return "Aluguel";
  if (property.purpose === "novos") return property.launchStatus || "Lançamento";
  return "Venda";
}

function monthlyTotal(property) {
  if (property.purpose !== "alugar") return "";
  const total = property.price + (property.condo || 0) + (property.iptuPeriod === "MONTHLY" ? property.iptu || 0 : 0);
  return total > property.price ? `<span class="monthly-total">Total mensal informado: <strong>${currency(total)}</strong></span>` : "";
}

function propertyCardCosts(property) {
  const items = [];
  if (property.condo) items.push(`<span><small>Condomínio</small><strong>${currency(property.condo)}</strong></span>`);
  if (property.iptu) items.push(`<span><small>IPTU</small><strong>${currency(property.iptu)}${property.iptuPeriod === "YEARLY" ? "/ano" : property.iptuPeriod === "MONTHLY" ? "/mês" : ""}</strong></span>`);
  return items.length ? items.join("") : `<span class="costs-pending">Despesas adicionais sob consulta</span>`;
}

