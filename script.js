function parseHash() {
  const raw = location.hash.slice(1) || "inicio";
  const [path, query = ""] = raw.split("?");
  return { path, params: new URLSearchParams(query) };
}

function normalized(text) {
  return String(text || "").normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

function filterProperties(params, favoritesOnly = false) {
  const purpose = params.get("finalidade") || "";
  const type = params.get("tipo") || "";
  const local = normalized(params.get("local"));
  const maxPrice = Number(params.get("preco")) || 0;
  const bedrooms = Number(params.get("quartos")) || 0;
  const suites = Number(params.get("suites")) || 0;
  const parking = Number(params.get("vagas")) || 0;
  const bathrooms = Number(params.get("banheiros")) || 0;
  const areaMin = Number(params.get("areaMin")) || 0;
  const code = normalized(params.get("codigo"));
  const requestedFeatures = params.getAll("caracteristicas");

  return properties.filter(property => {
    if (favoritesOnly && !favorites.includes(property.id)) return false;
    if (purpose && property.purpose !== purpose) return false;
    if (type && property.type !== type) return false;
    if (local && !normalized(`${property.neighborhood} ${property.city} ${property.title} ${property.building || ""}`).includes(local)) return false;
    if (maxPrice && property.price > maxPrice) return false;
    if (bedrooms && property.bedrooms < bedrooms) return false;
    if (suites && (property.suites ?? 0) < suites) return false;
    if (parking && property.parking < parking) return false;
    if (bathrooms && property.bathrooms < bathrooms) return false;
    if (areaMin && property.area < areaMin) return false;
    if (code && !normalized(property.fullCode).includes(code)) return false;
    if (requestedFeatures.some(feature => !property.features.includes(feature))) return false;
    return true;
  });
}

function filterChips(params) {
  const labels = {
    finalidade: { comprar: "Comprar", alugar: "Alugar", novos: "Lançamentos" },
    tipo: null,
    local: null,
    preco: value => `Até ${currency(Number(value))}`,
    quartos: value => `${value}+ quartos`,
    suites: value => `${value}+ suítes`,
    vagas: value => `${value}+ vagas`,
    banheiros: value => `${value}+ banheiros`,
    areaMin: value => `A partir de ${value} m²`,
    codigo: value => `Código ${value}`,
    caracteristicas: value => value[0].toUpperCase() + value.slice(1)
  };
  const chips = [];
  for (const [key, value] of params.entries()) {
    if (key === "pagina" || key === "ordem" || !value) continue;
    const formatter = labels[key];
    let label = value;
    if (typeof formatter === "function") label = formatter(value);
    else if (formatter && formatter[value]) label = formatter[value];
    chips.push(`<span class="filter-chip">${label}</span>`);
  }
  return chips.join("");
}

